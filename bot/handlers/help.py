        "стресс, кофеин, экранное время, физическую активность "
        "и дневной сон.\n\n"

        "📊 Моя статистика\n"
        "Показывает основные средние показатели по твоим чек-инам.\n\n"

        "📈 Первый отчёт\n"
        "После первой недели наблюдений показывает общий результат. "
        "Для отчёта нужно минимум 5 заполненных дней из первых 7.\n\n"

        "🔎 Анализ\n"
        "Ищет статистические связи между показателями сна "
